"""Branded PDF generation (ReportLab). Every official document carries the OmniTeckno header and a
verification footer. Kept free of Django model imports so it can be tested on its own."""
import io
from datetime import date
from pathlib import Path

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.units import mm
from reportlab.pdfgen import canvas
from reportlab.platypus import Table, TableStyle

LOGO = Path(__file__).resolve().parent / "assets" / "omniteckno-logo.png"
BRAND = colors.HexColor("#00AEFF")
BLACK = colors.black
MUTED = colors.HexColor("#5B6573")
BORDER = colors.HexColor("#E3E8EF")
W, H = A4


class BrandedDocument:
    """A4 document with black OmniTeckno header band, title block and footer."""

    def __init__(self, title, institution, subtitle="", reference=""):
        self.buf = io.BytesIO()
        self.c = canvas.Canvas(self.buf, pagesize=A4)
        self.c.setTitle(title)
        self.c.setAuthor("OmniEducation by OmniTeckno")
        self.title, self.institution, self.subtitle, self.reference = title, institution, subtitle, reference
        self.y = 0
        self._page_chrome()

    def _page_chrome(self):
        c = self.c
        c.setFillColor(BLACK)
        c.rect(0, H - 32 * mm, W, 32 * mm, stroke=0, fill=1)
        if LOGO.exists():
            c.drawImage(str(LOGO), 15 * mm, H - 26 * mm, width=52 * mm, height=20 * mm,
                        preserveAspectRatio=True, mask="auto")
        c.setFillColor(colors.white)
        c.setFont("Helvetica-Bold", 13)
        c.drawRightString(W - 15 * mm, H - 15 * mm, self.institution)
        c.setFont("Helvetica", 9)
        c.setFillColor(BRAND)
        c.drawRightString(W - 15 * mm, H - 21 * mm, "OmniEducation")
        c.setFillColor(BRAND)
        c.rect(0, H - 33.5 * mm, W, 1.5 * mm, stroke=0, fill=1)
        c.setFillColor(BLACK)
        c.setFont("Helvetica-Bold", 18)
        c.drawString(15 * mm, H - 47 * mm, self.title)
        c.setFont("Helvetica", 10)
        c.setFillColor(MUTED)
        if self.subtitle:
            c.drawString(15 * mm, H - 53 * mm, self.subtitle)
        if self.reference:
            c.drawRightString(W - 15 * mm, H - 47 * mm, self.reference)
        c.drawRightString(W - 15 * mm, H - 53 * mm, f"Issued {date.today():%d %b %Y}")
        # footer
        c.setStrokeColor(BORDER)
        c.line(15 * mm, 18 * mm, W - 15 * mm, 18 * mm)
        c.setFont("Helvetica", 8)
        c.drawString(15 * mm, 12 * mm, "Generated by OmniEducation · OmniTeckno, an OmniOS company")
        c.drawRightString(W - 15 * mm, 12 * mm, f"Page {c.getPageNumber()}")
        self.y = H - 62 * mm

    def ensure_space(self, needed):
        if self.y - needed < 25 * mm:
            self.c.showPage()
            self._page_chrome()

    def heading(self, text):
        self.ensure_space(12 * mm)
        self.c.setFillColor(BLACK)
        self.c.setFont("Helvetica-Bold", 12)
        self.c.drawString(15 * mm, self.y, text)
        self.y -= 7 * mm

    def paragraph(self, text, size=10, leading=14):
        from reportlab.lib.styles import ParagraphStyle
        from reportlab.platypus import Paragraph

        p = Paragraph(text, ParagraphStyle("p", fontName="Helvetica", fontSize=size, leading=leading))
        _, h = p.wrap(W - 30 * mm, self.y)
        self.ensure_space(h + 4 * mm)
        p.drawOn(self.c, 15 * mm, self.y - h)
        self.y -= h + 5 * mm

    def key_values(self, pairs, cols=2):
        rows, row = [], []
        for k, v in pairs:
            row += [k, str(v if v not in (None, "") else "—")]
            if len(row) == cols * 2:
                rows.append(row)
                row = []
        if row:
            rows.append(row + [""] * (cols * 2 - len(row)))
        col_w = (W - 30 * mm) / (cols * 2)
        t = Table(rows, colWidths=[col_w * 0.8, col_w * 1.2] * cols)
        t.setStyle(TableStyle([
            ("FONT", (0, 0), (-1, -1), "Helvetica", 9),
            *[("FONT", (i, 0), (i, -1), "Helvetica-Bold", 9) for i in range(0, cols * 2, 2)],
            ("TEXTCOLOR", (0, 0), (-1, -1), BLACK),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
        ]))
        self._draw(t)

    def table(self, header, rows, col_widths=None, align_right=()):
        data = [header, *rows]
        t = Table(data, colWidths=col_widths, repeatRows=1)
        style = [
            ("FONT", (0, 0), (-1, 0), "Helvetica-Bold", 9),
            ("FONT", (0, 1), (-1, -1), "Helvetica", 9),
            ("BACKGROUND", (0, 0), (-1, 0), BLACK),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("LINEBELOW", (0, 0), (-1, -1), 0.5, BORDER),
            ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#F7F9FB")]),
            ("TOPPADDING", (0, 0), (-1, -1), 5),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
        ]
        for col in align_right:
            style.append(("ALIGN", (col, 0), (col, -1), "RIGHT"))
        t.setStyle(TableStyle(style))
        self._draw(t)

    def total_box(self, label, value):
        self.ensure_space(14 * mm)
        c = self.c
        c.setFillColor(BLACK)
        c.roundRect(W - 85 * mm, self.y - 11 * mm, 70 * mm, 11 * mm, 2 * mm, stroke=0, fill=1)
        c.setFillColor(colors.white)
        c.setFont("Helvetica", 9)
        c.drawString(W - 81 * mm, self.y - 7 * mm, label)
        c.setFillColor(BRAND)
        c.setFont("Helvetica-Bold", 11)
        c.drawRightString(W - 19 * mm, self.y - 7 * mm, value)
        self.y -= 16 * mm

    def stamp(self, text):
        self.ensure_space(14 * mm)
        self.c.setStrokeColor(BRAND)
        self.c.setFillColor(BRAND)
        self.c.setFont("Helvetica-Bold", 10)
        self.c.roundRect(15 * mm, self.y - 10 * mm, 80 * mm, 10 * mm, 2 * mm, stroke=1, fill=0)
        self.c.drawString(19 * mm, self.y - 6.5 * mm, text)
        self.y -= 15 * mm

    def signature(self, label):
        self.ensure_space(22 * mm)
        self.y -= 12 * mm
        self.c.setStrokeColor(BLACK)
        self.c.line(15 * mm, self.y, 75 * mm, self.y)
        self.c.setFont("Helvetica", 9)
        self.c.setFillColor(MUTED)
        self.c.drawString(15 * mm, self.y - 5 * mm, label)
        self.y -= 10 * mm

    def _draw(self, flowable):
        _, h = flowable.wrap(W - 30 * mm, self.y)
        self.ensure_space(h + 4 * mm)
        flowable.drawOn(self.c, 15 * mm, self.y - h)
        self.y -= h + 6 * mm

    def render(self):
        self.c.save()
        return self.buf.getvalue()


def student_id_card(*, institution, name, student_no, level, valid_until, mode_label, photo=None):
    """CR80-sized ID card (85.6 x 54 mm)."""
    buf = io.BytesIO()
    size = (85.6 * mm, 54 * mm)
    c = canvas.Canvas(buf, pagesize=size)
    c.setTitle(f"Student ID – {name}")
    cw, ch = size
    c.setFillColor(BLACK)
    c.rect(0, 0, cw, ch, stroke=0, fill=1)
    c.setFillColor(BRAND)
    c.rect(0, ch - 2 * mm, cw, 2 * mm, stroke=0, fill=1)
    if LOGO.exists():
        c.drawImage(str(LOGO), 4 * mm, ch - 14 * mm, width=28 * mm, height=10 * mm, preserveAspectRatio=True, mask="auto")
    c.setFillColor(colors.white)
    c.setFont("Helvetica-Bold", 8)
    c.drawRightString(cw - 4 * mm, ch - 8 * mm, institution[:34])
    c.setFillColor(BRAND)
    c.setFont("Helvetica-Bold", 6.5)
    c.drawRightString(cw - 4 * mm, ch - 12 * mm, f"{mode_label.upper()} STUDENT ID")
    # photo (or a placeholder when none is on file / it cannot be read)
    drawn = False
    if photo:
        try:
            from reportlab.lib.utils import ImageReader
            c.drawImage(ImageReader(io.BytesIO(photo)), 4 * mm, 6 * mm, width=20 * mm, height=24 * mm,
                        preserveAspectRatio=True, anchor="c", mask="auto")
            drawn = True
        except Exception:  # noqa: BLE001 - a bad image must not block the ID card
            drawn = False
    c.setStrokeColor(BRAND)
    c.roundRect(4 * mm, 6 * mm, 20 * mm, 24 * mm, 1.5 * mm, stroke=1, fill=0)
    if not drawn:
        c.setFillColor(MUTED)
        c.setFont("Helvetica", 5.5)
        c.drawCentredString(14 * mm, 17 * mm, "PHOTO")
    c.setFillColor(colors.white)
    c.setFont("Helvetica-Bold", 10)
    c.drawString(28 * mm, 26 * mm, name[:28])
    c.setFont("Helvetica", 7)
    c.setFillColor(colors.HexColor("#C9D1DB"))
    c.drawString(28 * mm, 21 * mm, level[:40])
    c.setFillColor(BRAND)
    c.setFont("Courier-Bold", 9)
    c.drawString(28 * mm, 14 * mm, student_no)
    c.setFillColor(colors.HexColor("#C9D1DB"))
    c.setFont("Helvetica", 6)
    c.drawString(28 * mm, 8 * mm, f"Valid until {valid_until:%d %b %Y}")
    c.save()
    return buf.getvalue()
